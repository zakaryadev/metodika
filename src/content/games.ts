import type { CategoryId } from "./types";

export type GameKind =
  | "quiz"
  | "truefalse"
  | "memory"
  | "match"
  | "flashcards"
  | "fillblank"
  | "categorize"
  | "wordsearch"
  | "crossword"
  | "hangman"
  | "speed"
  | "wheel"
  | "anagram"
  | "ordering"
  | "scenario"
  | "finderror";

export type QuizData = {
  questions: { q: string; options: string[]; answer: number; explain?: string }[];
};
export type TrueFalseData = {
  items: { statement: string; isTrue: boolean; explain?: string }[];
};
export type MemoryData = { pairs: { a: string; b: string }[] };
export type MatchData = { pairs: { left: string; right: string }[] };
export type FlashcardsData = { cards: { front: string; back: string }[] };
export type FillBlankData = {
  items: { sentence: string; answer: string; hint?: string }[];
};
export type CategorizeData = {
  groups: string[];
  items: { text: string; group: string }[];
};
export type WordSearchData = { words: string[]; size: number };
export type CrosswordData = { entries: { word: string; clue: string }[] };
export type HangmanData = { items: { word: string; hint: string }[] };
export type SpeedData = {
  seconds: number;
  questions: { q: string; options: string[]; answer: number }[];
};
export type WheelData = { items: { q: string; a: string }[] };
export type AnagramData = { items: { word: string; hint: string }[] };
export type OrderingData = { items: { prompt: string; steps: string[] }[] };
export type FindErrorData = {
  items: { parts: string[]; errorIndex: number; explain: string }[];
};
export type ScenarioNode = {
  text: string;
  options?: { label: string; next: string }[];
  outcome?: "good" | "bad" | "neutral";
  feedback?: string;
};
export type ScenarioData = { start: string; nodes: Record<string, ScenarioNode> };

type Base = {
  slug: string;
  title: string;
  description: string;
  instruction: string;
  category: CategoryId;
  plays: number;
};

export type Game =
  | (Base & { kind: "quiz"; data: QuizData })
  | (Base & { kind: "truefalse"; data: TrueFalseData })
  | (Base & { kind: "memory"; data: MemoryData })
  | (Base & { kind: "match"; data: MatchData })
  | (Base & { kind: "flashcards"; data: FlashcardsData })
  | (Base & { kind: "fillblank"; data: FillBlankData })
  | (Base & { kind: "categorize"; data: CategorizeData })
  | (Base & { kind: "wordsearch"; data: WordSearchData })
  | (Base & { kind: "crossword"; data: CrosswordData })
  | (Base & { kind: "hangman"; data: HangmanData })
  | (Base & { kind: "speed"; data: SpeedData })
  | (Base & { kind: "wheel"; data: WheelData })
  | (Base & { kind: "anagram"; data: AnagramData })
  | (Base & { kind: "ordering"; data: OrderingData })
  | (Base & { kind: "scenario"; data: ScenarioData })
  | (Base & { kind: "finderror"; data: FindErrorData });

